#!/usr/bin/env python3

import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.colors import ListedColormap
from scripts.utils.helpers import setup_logger

def get_chaingroup(chain, chaingroups):
    for group, chains in chaingroups.items():
        if chain in chains:
            return group
    return None

def format_residue(chain, res_num):
    return f"{chain}:{res_num}"

def label_sort_key(label):
    if ':' in label:
        chain, res = label.split(':', 1)
        try:
            return (chain, int(res))
        except:
            return (chain, res)
    else:
        try:
            return ('@', int(label))  # numbers first
        except:
            return (label, 0)         # names last

def main(logfile : str =None, hbonds_parsed: str = None, hbonds_ext : str =None, domains : dict = {}, chaingroups: dict = {}, 
         group1: str = None, group2 : str = None, outfiles : list = []):
    """
    Plot extended hydrogen bond prediction results.

    Arguments:
        logfile       : Path to the log file.
        hbonds_parsed : Path to the .csv file with the parsed hydrogen bond prediction results.
        hbonds_ext    : Path to the .csv file with the extended hydrogen bond prediction results, with additional data about atoms, residues and domains.
        domains         : Dictionary of domains in the structure.
        chaingroups     : Dictionary of groups and chains in them.
        group1            : First atom group for hydrogen bond analysis.
        group2            : Second atom group for hydrogen bond analysis.
        outfiles  : List of output files generated by the analysis.
    """

    ##### Initialize logger
    logger = setup_logger("analysis", logfile)

    hbonds_ori = pd.read_csv(hbonds_parsed)
    hbonds_df = pd.read_csv(hbonds_ext)

    ##########  Plots per group
    # 2 groups
    fig, axes = plt.subplots(2, 1, figsize=(10, 5*2))
    if hbonds_df.empty:
        plt.text(0.5, 0.5, "No hydrogen bonds found", ha='center', va='center')
        plt.axis('off')
    else: 
        for i, group in enumerate([group1, group2]):
            # If group is a chain ID
            if len(group) == 1 and group.isalpha():
                donor_df = hbonds_df[hbonds_df['donor_chain'] == group]
                acceptor_df = hbonds_df[hbonds_df['acceptor_chain'] == group]
                group_domains = get_chaingroup(group, chaingroups)
                chains_donor = donor_df['donor_chain'].unique().tolist()
                axes[i].scatter(donor_df['donor_res_num_adjusted'], 
                                donor_df['frame%'], 
                                color='black', s=30, label=f'Donor {group}')
                axes[i].scatter(
                    acceptor_df['acceptor_res_num_adjusted'], 
                    acceptor_df['frame%'],
                    color='black', s=30, marker='o', facecolors='none', label=f'Acceptor {group}'
                )
                axes[i].legend()
            # If group is a predefined group (e.g., "Protein", "DNA")
            elif group in ["Protein", "DNA"]:
                donor_df = hbonds_df[hbonds_df['donor_group'] == group]
                acceptor_df = hbonds_df[hbonds_df['acceptor_group'] == group]

                group_domains = group if group in domains.keys() else None

                chains_donor = donor_df['donor_chain'].unique().tolist()
                chains_acceptor = acceptor_df['acceptor_chain'].unique().tolist()

                # Consistent color mapping for BOTH donor and acceptor
                tab10_colors = plt.cm.tab10.colors
                all_chains = sorted(set(chains_donor) | set(chains_acceptor))

                chain_to_color = {
                    chain: tab10_colors[i % 10]
                    for i, chain in enumerate(all_chains)
                }

                # -------------------
                # Donors
                # -------------------
                for chain in chains_donor:
                    mask = donor_df['donor_chain'] == chain
                    color = chain_to_color[chain]

                    axes[i].scatter(
                        donor_df.loc[mask, 'donor_res_num_adjusted'],
                        donor_df.loc[mask, 'frame%'],
                        facecolors=color,
                        edgecolors=color,
                        marker='o',
                        s=30,
                        label=f"Donor {chain}"
                    )

                # -------------------
                # Acceptors
                # -------------------
                for chain in chains_acceptor:
                    mask = acceptor_df['acceptor_chain'] == chain
                    color = chain_to_color[chain]

                    axes[i].scatter(
                        acceptor_df.loc[mask, 'acceptor_res_num_adjusted'],
                        acceptor_df.loc[mask, 'frame%'],
                        facecolors='none',
                        edgecolors=color,
                        marker='o',
                        s=30,
                        label=f"Acceptor {chain}"
                    )

            # Color by domain if available
            if group_domains and group_domains in domains.keys():
                for domain in domains[group_domains]:
                    axes[i].axvspan(domain['start'], domain['end'], zorder=0, alpha=0.2, color=domain['color'], label=domain['label'])
            axes[i].set_xlabel('Residue Number (Adjusted)')
            axes[i].set_ylabel('Frame %')
            axes[i].set_title(f'Hydrogen Bonds for {group}')
            axes[i].grid(True, alpha=0.3)
            axes[i].legend()
    plt.tight_layout()
    plt.savefig(outfiles["hbonds_per_group"])
    plt.close()
    logger.info(f"Plot of hydrogen bonds per group saved as {outfiles['hbonds_per_group']}")


    ########## Hbonds per chain (if groups have multiple chains)
    for group in [group1, group2]:
        if group == "Protein" or group == "DNA":
            if hbonds_df.empty:
                plt.text(0.5, 0.5, "No hydrogen bonds found", ha='center', va='center')
                plt.axis('off')
            else:
                chains = hbonds_df[(hbonds_df['donor_group'] == group)]['donor_chain'].unique().tolist() + hbonds_df[(hbonds_df['acceptor_group'] == group)]['acceptor_chain'].unique().tolist()
                chains = list(set(chains))
                nchains = len(chains)
                logger.debug(f"Group {group} has {nchains} chains: {chains}")
                fig, axes = plt.subplots(max(nchains,1), 1, figsize=(10, 5*max(nchains,1)))
                if nchains == 1:
                    axes = [axes]
                if group == "Protein":
                    if nchains < 1:
                        plt.text(0.5, 0.5, "No hydrogen bonds found", ha='center', va='center')
                        plt.axis('off')
                        print("0 Chains found for 'Protein'")
                    else:
                        for i, chain in enumerate(chains):
                            donor_df = hbonds_df[hbonds_df['donor_chain'] == chain]
                            acceptor_df = hbonds_df[hbonds_df['acceptor_chain'] == chain]
                            axes[i].scatter(donor_df['donor_res_num_adjusted'], donor_df['frame%'], 
                                    color='black', s=30, label=f'Donor')
                            axes[i].scatter(acceptor_df['acceptor_res_num_adjusted'], acceptor_df['frame%'], 
                                    color='black', label=f'Acceptor', s=30, marker='o', facecolors='none')
                            axes[i].set_xlabel('Residue Number (Adjusted)')
                            axes[i].set_ylabel('Frame %')
                            axes[i].set_title(f'Hydrogen Bonds for Chain {chain}')
                            axes[i].grid(True, alpha=0.3)
                            # Color by domain if available
                            chain_group = get_chaingroup(chain, chaingroups)
                            if chain_group and chain_group in domains.keys():
                                    for domain in domains[chain_group]:
                                            axes[i].axvspan(domain['start'], domain['end'], zorder=0, alpha=0.2, color=domain['color'], label=domain['label'])    
                            axes[i].legend()
                    plt.tight_layout()
                    plt.savefig(outfiles[f"hbonds_prot_chains"])
                    plt.close()
                    logger.info(f"Plot of protein hydrogen bonds per chain saved as {outfiles[f'hbonds_prot_chains']}")
                elif group == "DNA": 
                    if nchains < 1:
                        plt.text(0.5, 0.5, "No hydrogen bonds found", ha='center', va='center')
                        plt.axis('off')
                        print("0 Chains found for 'DNA'")
                    else:
                        for i, chain in enumerate(chains):
                            donor_df = hbonds_df[hbonds_df['donor_chain'] == chain]
                            acceptor_df = hbonds_df[hbonds_df['acceptor_chain'] == chain]
                            axes[i].scatter(donor_df['donor_res_num_adjusted'], donor_df['frame%'], 
                                            color="black", s=30, label=f'Donor')
                            axes[i].scatter(acceptor_df['acceptor_res_num_adjusted'], acceptor_df['frame%'], 
                                            color="black", s=30, 
                                            label=f'Acceptor', marker='o', facecolors='none')
                            axes[i].set_xlabel('Residue Number (Adjusted)')
                            axes[i].set_ylabel('Frame %')
                            axes[i].set_title(f'Hydrogen Bonds for Chain {chain}')
                            axes[i].grid(True, alpha=0.3)
                            # Color by domain if available
                            chain_group = get_chaingroup(chain, chaingroups)
                            if chain_group and chain_group in domains.keys():
                                    for domain in domains[chain_group]:
                                            axes[i].axvspan(domain['start'], domain['end'], zorder=0, alpha=0.2, color=domain['color'], label=domain['label'])    
                            axes[i].legend()
                    plt.tight_layout()
                    plt.savefig(outfiles[f"hbonds_dna_chains"])
                    plt.close()
                    logger.info(f"Plot of DNA hydrogen bonds per chain saved as {outfiles[f'hbonds_dna_chains']}")


    ##### HEATMAPS ####
    total_frames = hbonds_ori['frame'].nunique()
    chains_df = hbonds_df.copy()

    for group in [group1, group2]:
        # If group is a chain ID
        if len(group) == 1 and group.isalpha():
            chains_df[f'{group}'] = np.where(
                hbonds_df['donor_chain'] == group,
                hbonds_df['donor_res_num_adjusted'],
                hbonds_df['acceptor_res_num_adjusted']
            )
        # If group is a predefined group (e.g., "Protein", "DNA")
        elif group == "Protein" or group == "DNA":
            chains_df[f'{group}'] = np.where(
                hbonds_df['donor_group'] == group,
                hbonds_df.apply(lambda row: format_residue(row['donor_chain'], row['donor_res_num_adjusted']), axis=1),
                hbonds_df.apply(lambda row: format_residue(row['acceptor_chain'], row['acceptor_res_num_adjusted']), axis=1)
            )

    df_pivot = chains_df.pivot_table(
        index=f'{group1}',
        columns=f'{group2}',
        values='count',
        aggfunc='sum',
    ) / total_frames

    # Sort by residue number (if group is chain ID) or by chain and residue number (if group is predefined)
    df_pivot = df_pivot.reindex(
        index=sorted(df_pivot.index, key=lambda x: label_sort_key(str(x))),
        columns=sorted(df_pivot.columns, key=lambda x: label_sort_key(str(x)))
    )


    fig, ax = plt.subplots(figsize=(12, 8))  # Bigger + ax
    if df_pivot.empty:
        plt.text(0.5, 0.5, "No hydrogen bonds found", ha='center', va='center')
        plt.axis('off')
    else:
        sns.heatmap(df_pivot, cmap='rocket_r', annot=False, linewidths=0.5, 
                    linecolor='lightgray', cbar_kws={'label': 'predicted bond count / total frames'}, ax=ax)
        ax.tick_params(axis='x', rotation=-90)
        ax.tick_params(axis='y', rotation=0)
        ax.set_xlabel(group2, fontsize=14)
        ax.set_ylabel(group1, fontsize=14)
        ax.set_title(f'Hydrogen Bonds between {group1} and {group2}', fontsize=16)
    plt.tight_layout()
    plt.savefig(outfiles[f"hbonds_heatmap"], dpi=300)
    plt.close()
    logger.info(f"Plot of hydrogen bonds heatmap saved as {outfiles[f'hbonds_heatmap']}")

    ##### HEATMAP (DNA base only) ####

    if "DNA" in [group1, group2]:
        total_frames = hbonds_ori['frame'].nunique()
        chains_df = hbonds_df.copy()

        # keep only interactions involving a base section on either side
        chains_df = chains_df[
            (chains_df['donor_section'] == 'base') |
            (chains_df['acceptor_section'] == 'base')
        ].copy()

        for group in [group1, group2]:
            # If group is a chain ID
            if len(group) == 1 and group.isalpha():
                chains_df[f'{group}'] = np.where(
                    chains_df['donor_chain'] == group,
                    chains_df['donor_res_num_adjusted'],
                    chains_df['acceptor_res_num_adjusted']
                )

            # If group is a predefined group (e.g., "Protein", "DNA")
            elif group == "Protein" or group == "DNA":
                chains_df[f'{group}'] = np.where(
                    chains_df['donor_group'] == group,
                    chains_df.apply(
                        lambda row: format_residue(row['donor_chain'], row['donor_res_num_adjusted']),
                        axis=1
                    ),
                    chains_df.apply(
                        lambda row: format_residue(row['acceptor_chain'], row['acceptor_res_num_adjusted']),
                        axis=1
                    )
                )

        df_pivot = chains_df.pivot_table(
            index=f'{group1}',
            columns=f'{group2}',
            values='count',
            aggfunc='sum',
        ) / total_frames

        df_pivot = df_pivot.reindex(
            index=sorted(df_pivot.index, key=lambda x: label_sort_key(str(x))),
            columns=sorted(df_pivot.columns, key=lambda x: label_sort_key(str(x)))
        )

        fig, ax = plt.subplots(figsize=(12, 8))
        if df_pivot.empty:
            plt.text(0.5, 0.5, "No hydrogen bonds found", ha='center', va='center')
            plt.axis('off')
        else:
            sns.heatmap(
                df_pivot,
                cmap='rocket_r',
                annot=False,
                linewidths=0.5,
                linecolor='lightgray',
                cbar_kws={'label': 'predicted bond count / total frames'},
                ax=ax
            )
            ax.tick_params(axis='x', rotation=-90)
            ax.tick_params(axis='y', rotation=0)
            ax.set_xlabel(group2, fontsize=14)
            ax.set_ylabel(group1, fontsize=14)
            ax.set_title(f'Hydrogen Bonds between {group1} and {group2} (base only)', fontsize=16)

        plt.tight_layout()
        plt.savefig(outfiles["hbonds_heatmap_base"], dpi=300)
        plt.close()

        logger.info(f"Plot of hydrogen bonds heatmap saved as {outfiles['hbonds_heatmap_base']}")

      
if __name__ == "__main__":
    main()