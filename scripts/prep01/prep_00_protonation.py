"""Assign fixed protonation states before LEaP adds hydrogens
"""
import re
import csv
import math
import subprocess
import sys
import tempfile
from pathlib import Path

# Protonation states aminoacids:
"""
pH Acide 3.0:
ASH (0), GLH (0), CYS (0), TYR (0), HIP (+1), LYS (+1), ARG (+1)

pH Physiological 7.4:
ASP (−1), GLU (−1), CYS (0), TYR (0), HID/HIE (0), LYS (+1), ARG (+1)

pH Base 9.0:
ASP (−1), GLU (−1), CYM (−1), TYR (0), HID/HIE (0), LYS (+1), ARG (+1)

To mind:
- At physiological pH, HID/HIE tautomerization is not trivial to predict, and the protonation state of histidine residues can significantly affect protein structure and function. Therefore, it is important to carefully consider the protonation states of histidines in your system, especially if they are involved in active sites or hydrogen bonding networks.
- At pH 9.0, the deprotonation of cysteine residues (CYM) can lead to the formation of disulfide bonds, which can stabilize protein structure. However, it is important to note that the formation of disulfide bonds is not always favorable and can depend on the specific protein and its environment. It is important to fix CONECT records to maintain the disulfide bonds in the final PDB file, as they are not automatically generated by LEaP. This can be done by manually adding the CONECT records for the disulfide bonds in the PDB file before running LEaP.
- For disulfides in LEaP, assign both residues as CYX and explicitly establish the SG–SG bond, or verify that your preparation workflow creates it. Adding CONECT records alone might not work.
"""

"""Assign fixed AMBER side-chain states before LEaP adds hydrogens.

Requires PROPKA and, for automatic neutral histidines, PDB2PQR in the
pipeline's Python environment. Input should be a hydrogen-free single model.
Disulfides remain CYX; their SG-SG bonds must be handled by the LEaP setup.
"""


ATOM_RECORDS = ('ATOM  ', 'HETATM')
STALE_REFERENCES = ('SSBOND', 'CONECT', 'ANISOU', 'LINK')
CANONICAL = {
    'ASH': 'ASP', 'GLH': 'GLU', 'HID': 'HIS', 'HIE': 'HIS',
    'HIP': 'HIS', 'LYN': 'LYS', 'CYM': 'CYS', 'CYX': 'CYS',
}
# Each pair is (protonated, deprotonated). None requires special handling.
STATES = {
    'ASP': ('ASH', 'ASP'), 'GLU': ('GLH', 'GLU'),
    'LYS': ('LYS', 'LYN'), 'CYS': ('CYS', 'CYM'),
    'HIS': ('HIP', None), 'TYR': ('TYR', None), 'ARG': ('ARG', None),
}
PROTEIN_NAMES = set(
    'ALA ARG ASN ASP CYS GLN GLU GLY HIS ILE LEU LYS MET PHE PRO SER THR TRP TYR VAL'.split()
)
HISTIDINE_HYDROGENS = {'HID': {'HD1'}, 'HIE': {'HE2'}}
REPORT_FIELDS = [
    'original_chain', 'original_residue', 'original_icode',
    'prepared_chain', 'prepared_residue', 'prepared_icode',
    'input_state', 'pka', 'assigned_state', 'reason', 'near_pka', 'target_ph',
]


def canonical(name): # Converts protonated original residues into their standard canonical names
    return CANONICAL.get(name, name)


def normalize_config(config): # Checks the params.yml 
    if config is None:
        return {'method': 'none'}
    if not isinstance(config, dict):
        raise ValueError('protonation must be a mapping')
    method = config.get('method', 'none')
    if method not in ('none', 'propka'): # Only propka installed
        raise ValueError('protonation.method must be none or propka')
    if method == 'none':
        return {'method': 'none'}

    ph = float(config.get('ph', 7.4)) # Default physiological pH
    window = float(config.get('review_pka_window', 1.0))
    if not math.isfinite(ph) or not 0 <= ph <= 14: # pH range allowed
        raise ValueError('pH must be finite and between 0 and 14')
    if not math.isfinite(window) or window < 0:
        raise ValueError('review_pka_window must be finite and nonnegative')
    overrides = config.get('overrides', []) # Exceptional manual overrides for residues with unusual chemistry
    if overrides is None:
        overrides = []
    if not isinstance(overrides, list):
        raise ValueError('overrides must be a list')
    return dict(method=method, ph=ph, review_pka_window=window, overrides=overrides)


def residue_key(line): # ID residues
    return line[21].strip(), int(line[22:26]), line[26].strip()


def is_hydrogen(line): # ID hydrogens by element or name
    name = line[12:16].strip()
    element = line[76:78].strip() or name.lstrip('0123456789')[:1]
    return element in ('H', 'D')


def residues(lines):
    found = {}
    for line in lines:
        if line.startswith('MODEL'):
            raise ValueError('Select one PDB model and remove its MODEL/ENDMDL records')
        if not line.startswith(ATOM_RECORDS):
            continue
        key, name = residue_key(line), line[17:20].strip()
        if key in found and found[key] != name:
            raise ValueError(f'Ambiguous residue identifier: {key}')
        found[key] = name
    return found


def predictor_input(lines, indices, states): # Predictor preparation of a temporary PDB for ProPKA
    """Use unique residue numbers in the temporary predictor PDB only."""
    output = []
    for line in lines:
        if line.startswith(STALE_REFERENCES):
            continue
        if line.startswith(ATOM_RECORDS):
            key = residue_key(line)
            line = (line[:17] + f'{states[key]:>3}' + line[20:22]
                    + f'{indices[key]:4d} ' + line[27:])
        output.append(line)
    return ''.join(output)


def run_predictor(command, work, logpath, failure_message): # Run of propka or pdb2pqr preparing the commands for the external call
    result = subprocess.run(command, cwd=work, capture_output=True, text=True)
    logpath.write_text(result.stdout + result.stderr)
    if result.returncode:
        raise RuntimeError(f'{failure_message}; inspect {logpath}')


def parse_pkas(text): # Output of propka by residue index and pKa value
    marker = 'SUMMARY OF THIS PREDICTION'
    if marker not in text:
        raise RuntimeError('PROPKA output has no prediction summary')
    pkas = {}
    for line in text.split(marker, 1)[1].splitlines():
        m = re.match(r'\s*(\S{2,3}?)\s*(\d+)\s', line)
        fields = line.split()
        if not m or m.group(1) not in STATES or len(fields) < 4:
            continue
        try:
            index, pka = int(m.group(2)), float(fields[-2].rstrip('*'))
        except ValueError:
            continue
        if index in pkas:
            raise RuntimeError(f'Duplicate PROPKA prediction: {index}')
        if not math.isfinite(pka):
            raise ValueError(f'Invalid PROPKA pKa for residue {index}')
        pkas[index] = pka
    return pkas


def run_propka(lines, prepared, indices, path, logger): # Call of propka through run_predictor and parses the pka values
    states = {key: canonical(name) for key, name in prepared.items()}
    with tempfile.TemporaryDirectory(prefix='propka_', dir=path.parent) as folder:
        work = Path(folder)
        (work / 'predictor.pdb').write_text(predictor_input(lines, indices, states))
        command = [sys.executable, '-m', 'propka', 'predictor.pdb',
                   '--display-coupled-residues']
        run_predictor(command, work, path.with_suffix('.propka.log'), 'PROPKA failed')
        outputs = list(work.glob('*.pka'))
        if len(outputs) != 1:
            raise RuntimeError(f'Expected one PROPKA .pka file, found {len(outputs)}')
        text = outputs[0].read_text()
        path.with_suffix('.pka').write_text(text)
    return parse_pkas(text)


def prepare_overrides(original, prepared, items): # Exceptions manually input. Useful for terminal residues, Histidine states and CYX (last one not tested until SSBONDS is implemented)
    """Map original IDs to prepared IDs, requiring unchanged residue order."""
    if len(original) != len(prepared):
        raise ValueError('pdb4amber changed residue count; explicit mapping needed')
    mapping = {}
    for (old_key, old_name), (key, name) in zip(original.items(), prepared.items()):
        if canonical(old_name) != canonical(name):
            raise ValueError('pdb4amber changed residue order/identity; mapping needed')
        mapping[old_key] = key

    overrides = {}
    for item in items:
        if not isinstance(item, dict):
            raise ValueError('Each override must be a mapping')
        old_key = (str(item.get('chain', '')).strip(), int(item['residue']),
                   str(item.get('insertion_code', '')).strip())
        if old_key not in mapping:
            raise ValueError(f'Override residue absent from original PDB: {old_key}')
        key = mapping[old_key]
        if key in overrides:
            raise ValueError(f'Duplicate override: {old_key}')
        if prepared[key] == 'CYX':
            raise ValueError('Do not titrate disulfide CYX residues')
        base = canonical(prepared[key])
        allowed = {state for state in STATES.get(base, ()) if state}
        if base == 'HIS':
            allowed.update(HISTIDINE_HYDROGENS)
        state = str(item['state']).upper()
        if state not in allowed:
            raise ValueError(f'Unsupported override {state} for {old_key} ({base})')
        overrides[key] = state
    return mapping, overrides

 
def terminal_residues(lines): # Detection of terminal residues based on TER records
    """Find protein segment endpoints from TER records and chain changes."""
    terminals, segment = set(), []
    for line in lines:
        if line.startswith('TER'):
            if segment:
                terminals.update((segment[0], segment[-1]))
                segment = []
        elif line.startswith(ATOM_RECORDS) and canonical(line[17:20].strip()) in PROTEIN_NAMES:
            key = residue_key(line)
            if segment and key[0] != segment[-1][0]:
                terminals.update((segment[0], segment[-1]))
                segment = []
            if not segment or key != segment[-1]:
                segment.append(key)
    if segment:
        terminals.update((segment[0], segment[-1]))
    return terminals


def choose_states(prepared, indices, pkas, overrides, old_keys, config, logger): # Selects the protonation states based on pKa values, overrides, and pH
    """Return assignments, histidines to optimize, report rows, and errors."""
    decisions, targets, rows, errors = {}, set(), [], []
    ph = config['ph']
    for key, name in prepared.items():
        base = canonical(name)
        if base not in STATES or name == 'CYX':
            continue
        pka = pkas.get(indices[key])
        state, reason = name, 'PROPKA'
        if key in overrides:
            state, reason = overrides[key], 'manual override'
        elif pka is None:
            reason = 'missing prediction'
            errors.append(f'{old_keys[key]}: no pKa prediction; supply override')
        else:
            protonated = ph < pka
            state = STATES[base][0 if protonated else 1]
            if base == 'HIS' and not protonated:
                targets.add(key)
                reason = 'pending PDB2PQR optimization'
            elif state is None:
                errors.append(f'{old_keys[key]}: unsupported deprotonated {base}')
        review = pka is not None and abs(ph - pka) <= config['review_pka_window']
        if review:
            logger.warning(f'Review {old_keys[key]}: pKa={pka:.2f}, pH={ph}')
        decisions[key] = state or name
        rows.append(dict(zip(REPORT_FIELDS, [
            *old_keys[key], *key, name, pka, state, reason, review, ph,
        ])))
    return decisions, targets, rows, errors


def protein_atoms(lines, prepared): # Checks if possible to do automatic histidine assignment 
    """Validate PDB2PQR input and collect the original protein heavy atoms."""
    unsupported = {name for name in prepared.values()
                   if canonical(name) not in PROTEIN_NAMES and name not in ('HOH', 'WAT')}
    if unsupported:
        raise ValueError('Automatic histidine assignment supports standard proteins and water. '
                         'Supply histidine overrides for inputs containing: '
                         + ', '.join(sorted(unsupported)))
    atoms = {}
    for line in lines:
        if not line.startswith(ATOM_RECORDS):
            continue
        if line[16].strip():
            raise ValueError('Resolve alternate conformations before automatic assignment')
        if is_hydrogen(line):
            raise ValueError('Automatic stage expects a hydrogen-free input PDB')
        key = residue_key(line)
        if canonical(prepared[key]) in PROTEIN_NAMES:
            atom_key = key, line[12:16].strip()
            if atom_key in atoms:
                raise ValueError(f'Duplicate input atom: {atom_key}')
            atoms[atom_key] = line
    return atoms


def read_pdb2pqr(text, prepared, indices):
    """Map output atoms back to prepared residues without guessing identities."""
    by_index = {index: key for key, index in indices.items()}
    states, hydrogens, coords = {}, {}, {}
    for line in text.splitlines():
        if not line.startswith(ATOM_RECORDS):
            continue
        index = int(line[22:26])
        if index not in by_index:
            raise ValueError(f'Unexpected PDB2PQR residue number: {index}')
        key = by_index[index]
        if line[21].strip() != key[0]:
            raise ValueError(f'PDB2PQR changed chain identity at {key}')
        if canonical(prepared[key]) not in PROTEIN_NAMES:
            continue
        state = line[17:20].strip()
        if canonical(state) != canonical(prepared[key]):
            raise ValueError(f'PDB2PQR changed residue identity at {key}')
        if key in states and states[key] != state:
            raise ValueError(f'Ambiguous PDB2PQR state at {key}')
        states[key] = state
        name = line[12:16].strip()
        if is_hydrogen(line):
            hydrogens.setdefault(key, set()).add(name)
            continue
        atom_key = key, name
        if atom_key in coords:
            raise ValueError(f'Duplicate PDB2PQR atom: {atom_key}')
        if not all(math.isfinite(float(line[i:i+8])) for i in (30, 38, 46)):
            raise ValueError(f'Invalid PDB2PQR coordinates: {atom_key}')
        coords[atom_key] = line[30:54]
    return states, hydrogens, coords


def pdb2pqr_histidines(lines, prepared, indices, decisions, targets, path, config, logger): # Runs pdb2pqr to choose HIS states based on Hbonding optimization
    original_atoms = protein_atoms(lines, prepared)
    prediction_states = {}
    for key, name in prepared.items():
        state = 'HIS' if key in targets else decisions.get(key, name)
        prediction_states[key] = 'HOH' if state == 'WAT' else state

    with tempfile.TemporaryDirectory(prefix='pdb2pqr_', dir=path.parent) as folder:
        work = Path(folder)
        (work / 'input.pdb').write_text(predictor_input(lines, indices, prediction_states))
        command = [sys.executable, '-c', 'from pdb2pqr.main import main; main()',
                   '--ff=AMBER', '--ffout=AMBER', '--keep-chain', '--nodebump',
                   '--titration-state-method=propka', '--with-ph', str(config['ph']),
                   '--pdb-output=optimized.pdb', 'input.pdb', 'optimized.pqr']
        run_predictor(command, work, path.with_suffix('.pdb2pqr.log'),
                      'Automatic histidine assignment failed')
        output = work / 'optimized.pdb'
        if not output.is_file():
            raise RuntimeError('PDB2PQR did not write optimized.pdb')
        text = output.read_text()
        path.with_suffix('.pdb2pqr.pdb').write_text(text)

    states, hydrogens, coords = read_pdb2pqr(text, prepared, indices)
    if coords.keys() != original_atoms.keys():
        raise ValueError('PDB2PQR added/removed or renamed protein heavy atoms; '
                         'explicit atom mapping needed')
    for key, requested in decisions.items():
        if key not in targets and key in states and states[key] != requested:
            raise ValueError(f'PDB2PQR changed requested state at {key}: '
                             f'{requested} -> {states[key]}')
    assignments = {}
    for key in targets:
        state = states.get(key)
        if state not in HISTIDINE_HYDROGENS:
            raise ValueError(f'PDB2PQR did not return neutral HID/HIE for {key}: {state}')
        ring_h = hydrogens.get(key, set()) & {'HD1', 'HE2'}
        if ring_h != HISTIDINE_HYDROGENS[state]:
            raise ValueError(f'PDB2PQR state/hydrogens disagree at {key}')
        assignments[key] = state
        logger.info(f'Automatic histidine {key}: {state} (PDB2PQR optimization)')
    changed = sum(original_atoms[key][30:54] != xyz for key, xyz in coords.items())
    logger.info(f'Transferring optimized protein coordinates; {changed} atom records differ. '
                'Original waters/components are retained.')
    return assignments, coords


def write_report(path, rows): # Output of the protonation report in CSV format
    report = path.with_suffix('.protonation.csv')
    with report.open('w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=REPORT_FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    return report


def write_assigned_pdb(path, lines, decisions, coords):
    output = []
    for line in lines:
        if line.startswith(ATOM_RECORDS):
            key = residue_key(line)
            if key in decisions:
                line = line[:17] + f'{decisions[key]:>3}' + line[20:]
            atom_key = key, line[12:16].strip()
            if atom_key in coords:
                line = line[:30] + coords[atom_key] + line[54:]
        output.append(line)
    path.with_suffix('.unassigned.pdb').write_text(''.join(lines))
    path.write_text(''.join(output))


def assign_protonation(pdbfile, original_pdb, config, logger):
    config = normalize_config(config)
    if config['method'] == 'none':
        return str(pdbfile)

    path = Path(pdbfile).resolve()
    lines = path.read_text().splitlines(keepends=True)
    prepared = residues(lines)
    original = residues(Path(original_pdb).read_text().splitlines(keepends=True))
    mapping, overrides = prepare_overrides(original, prepared, config['overrides'])
    old_keys = {key: old_key for old_key, key in mapping.items()}
    indices = {key: index for index, key in enumerate(prepared, 1)}
    if len(indices) > 9999:
        raise ValueError('Predictor PDB exceeds 9999 residues; mmCIF support needed')

    pkas = run_propka(lines, prepared, indices, path, logger)
    decisions, targets, rows, errors = choose_states(
        prepared, indices, pkas, overrides, old_keys, config, logger)
    for key in sorted(terminal_residues(lines)):
        if decisions.get(key, prepared[key]) in {'ASH', 'GLH', 'LYN', 'CYM'}:
            errors.append(f'{old_keys[key]}: terminal {decisions[key]} is not validated '
                          'in this pipeline; review terminal chemistry and AMBER templates')

    coords = {}
    if targets and not errors:
        try:
            automatic, coords = pdb2pqr_histidines(
                lines, prepared, indices, decisions, targets, path, config, logger)
            decisions.update(automatic)
            for row in rows:
                key = (row['prepared_chain'], row['prepared_residue'], row['prepared_icode'])
                if key in automatic:
                    row['assigned_state'] = automatic[key]
                    row['reason'] = 'PDB2PQR hydrogen-bond optimization'
        except (ValueError, RuntimeError, OSError) as exc:
            errors.append(str(exc))

    report = write_report(path, rows)
    logger.warning('Review PROPKA coupled-group output; assignments assume independent sites. '
                   'Termini, DNA, phosphoresidues, ligands and metals retain input/default chemistry.')
    if errors:
        raise ValueError('Protonation needs review:\n' + '\n'.join(errors) + f'\nReport: {report}')
    write_assigned_pdb(path, lines, decisions, coords)
    logger.info(f'Assigned protein side-chain states at pH {config["ph"]}; report: {report}')
    return str(path)
